METRICS = list(LOWER_IS_BETTER)


def find_prediction(out_dir: Path) -> Path | None:
    paths = sorted(out_dir.glob("neural_field_predictions_*.npz"), key=lambda p: p.stat().st_mtime, reverse=True)
    return paths[0] if paths else None


def configs_for_base(base: Path | None) -> list[dict]:
    configs = []
    for cfg in DEFAULT_CONFIGS:
        one = dict(cfg)
        if base is not None:
            one["out_dir"] = str(base / str(one["out_rel"]))
        configs.append(one)
    return configs


def read_summary(out_dir: Path) -> dict:
    paths = sorted(out_dir.glob("neural_field_summary_*.json"), key=lambda p: p.stat().st_mtime, reverse=True)
    if not paths:
        return {}
    return json.loads(paths[0].read_text(encoding="utf-8"))


def selected_alpha(pred: np.lib.npyio.NpzFile, summary: dict) -> float:
    if "selected_alpha" in pred.files:
        return float(np.asarray(pred["selected_alpha"]).reshape(-1)[0])
    alpha = summary.get("alpha_selection", {}).get("best_alpha")
    return float(alpha) if alpha is not None else float("nan")


def metric_means(rows: list[dict[str, float | str]]) -> dict[str, float]:
    return {metric: float(np.mean([float(r[metric]) for r in rows])) for metric in METRICS}


def copy_metric_csvs(src_dir: Path, dst_dir: Path, labels: list[str]) -> None:
    dst_dir.mkdir(parents=True, exist_ok=True)
    for label in ["reference", *labels]:
        src = src_dir / f"identity_bootstrap_pair_metrics_{label}.csv"
        if src.exists():
            shutil.copyfile(src, dst_dir / src.name)


def run_final_table(stats_dir: Path, baseline: str, methods: list[str], n_boot: int, seed: int) -> None:
    if not methods:
        return
    here = Path(__file__).resolve().parent
    cmd = [
        sys.executable,
        str(here / "significance.py"),
        "--out",
        str(stats_dir),
        "--baseline",
        baseline,
        "--methods",
        ",".join(methods),
        "--n-boot",
        str(n_boot),
        "--seed",
        str(seed),
    ]
    subprocess.run(cmd, check=True)


def render_md_report(out_dir: Path, configs: list[dict], rows: list[dict], missing: list[dict]) -> None:
    by_label = {row["label"]: row for row in rows}
    ref = by_label.get("reference")
    lines = [
        "# Ablation Sweep Processing",
        "",
        "This file is generated by `sweep.py`.",
        "",
        "## Available Runs",
        "",
        "| Label | Group | alpha | ROI RMSE | Edge p95 | Flip % | Description |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in rows:
        lines.append(
            "| "
            + " | ".join(
                [
                    row["label"],
                    row["group"],
                    f"{row['selected_alpha']:.3g}",
                    f"{row['roi_rmse']:.4f}",
                    f"{row['edge_strain_p95']:.4f}",
                    f"{row['normal_flip_pct']:.4f}",
                    row["description"],
                ]
            )
            + " |"
        )
    if ref:
        lines.extend(
            [
                "",
                "## Deltas vs Reference",
                "",
                "Negative delta means lower error than the reference hybrid.",
                "",
                "| Label | Δ ROI RMSE | Δ Dorsum RMSE | Δ Tip RMSE | Δ Edge p95 | Δ Flip % |",
                "| --- | ---: | ---: | ---: | ---: | ---: |",
            ]
        )
        for row in rows:
            if row["label"] == "reference":
                continue
            lines.append(
                "| "
                + " | ".join(
                    [
                        row["label"],
                        f"{row['delta_roi_rmse']:.4f}",
                        f"{row['delta_dorsum_rmse']:.4f}",
                        f"{row['delta_tip_rmse']:.4f}",
                        f"{row['delta_edge_strain_p95']:.4f}",
                        f"{row['delta_normal_flip_pct']:.4f}",
                    ]
                )
                + " |"
            )
    if missing:
        lines.extend(
            [
                "",
                "## Missing Runs",
                "",
                "| Label | Expected directory |",
                "| --- | --- |",
            ]
        )
        for item in missing:
            lines.append(f"| {item['label']} | `{item['out_dir']}` |")
    lines.extend(
        [
            "",
            "## Generated Outputs",
            "",
            f"- `{out_dir / 'tradeoff.csv'}`",
            f"- `{out_dir / 'ablation.csv'}`",
            f"- `{out_dir / 'tradeoff_stats/final_statistical_table.csv'}`",
            f"- `{out_dir / 'ablation_stats/final_statistical_table.csv'}`",
        ]
    )
    (out_dir / "notes.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", default="../data")
    parser.add_argument("--out", default="../results/sweep")
    parser.add_argument("--base", default=None, help="Output base containing main/ and sweep/ prediction folders.")
    parser.add_argument("--n-boot", type=int, default=10000)
    parser.add_argument("--seed", type=int, default=2051)
    args = parser.parse_args()

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    pair_dir = out_dir / "pair_metrics"
    pair_dir.mkdir(parents=True, exist_ok=True)

    _, by_id = load_rows(Path(args.repo))
    configs = configs_for_base(Path(args.base) if args.base else None)
    rows: list[dict] = []
    missing: list[dict] = []
    for cfg in configs:
        pred_path = find_prediction(Path(cfg["out_dir"]))
        if pred_path is None:
            missing.append({"label": cfg["label"], "out_dir": cfg["out_dir"]})
            continue
        pred = np.load(pred_path, allow_pickle=True)
        if "hybrid_selected_pred" not in pred.files:
            missing.append({"label": cfg["label"], "out_dir": cfg["out_dir"], "reason": "missing hybrid_selected_pred"})
            continue
        pairs = [(str(a), str(b)) for a, b in pred["test_pairs"].tolist()]
        metric_rows = metric_rows_for_method(by_id, pairs, np.asarray(pred["hybrid_selected_pred"]))
        write_csv(pair_dir / f"identity_bootstrap_pair_metrics_{cfg['label']}.csv", metric_rows)
        means = metric_means(metric_rows)
        summary = read_summary(Path(cfg["out_dir"]))
        row = {
            **cfg,
            **means,
            "selected_alpha": selected_alpha(pred, summary),
            "prediction_file": str(pred_path),
        }
        rows.append(row)

    ref = next((r for r in rows if r["label"] == "reference"), None)
    if ref:
        for row in rows:
            for metric in METRICS:
                row[f"delta_{metric}"] = float(row[metric] - ref[metric])

    fieldnames = [
        "label",
        "group",
        "description",
        "selected_alpha",
        "edge_weight",
        "lap_weight",
        "strain_weight",
        "source_pca_dim",
        *METRICS,
        *(f"delta_{m}" for m in METRICS),
        "prediction_file",
    ]
    with (out_dir / "all_available_hybrid_means.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: row.get(k, "") for k in fieldnames})

    p13_labels = [r["label"] for r in rows if r["group"] in {"p1_3_tradeoff", "p1_3_tradeoff_optional"}]
    p14_labels = [r["label"] for r in rows if r["group"] == "p1_4_ablation"]

    with (out_dir / "tradeoff.csv").open("w", newline="", encoding="utf-8") as f:
        p13_fields = [
            "label",
            "description",
            "selected_alpha",
            "edge_weight",
            "lap_weight",
            "strain_weight",
            "roi_rmse",
            "edge_strain_p95",
            "normal_flip_pct",
            "delta_roi_rmse",
            "delta_edge_strain_p95",
            "delta_normal_flip_pct",
            "prediction_file",
        ]
        writer = csv.DictWriter(f, fieldnames=p13_fields)
        writer.writeheader()
        for row in rows:
            if row["label"] == "reference" or row["label"] in p13_labels:
                writer.writerow({k: row.get(k, "") for k in p13_fields})

    with (out_dir / "ablation.csv").open("w", newline="", encoding="utf-8") as f:
        p14_fields = [
            "label",
            "description",
            "selected_alpha",
            "roi_rmse",
            "landmark_rmse",
            "dorsum_rmse",
            "tip_rmse",
            "edge_strain_p95",
            "normal_flip_pct",
            "delta_roi_rmse",
            "delta_landmark_rmse",
            "delta_dorsum_rmse",
            "delta_tip_rmse",
            "delta_edge_strain_p95",
            "delta_normal_flip_pct",
            "prediction_file",
        ]
        writer = csv.DictWriter(f, fieldnames=p14_fields)
        writer.writeheader()
        for row in rows:
            if row["label"] == "reference" or row["label"] in p14_labels:
                writer.writerow({k: row.get(k, "") for k in p14_fields})

    if ref:
        p13_stats = out_dir / "tradeoff_stats"
        p14_stats = out_dir / "ablation_stats"
        copy_metric_csvs(pair_dir, p13_stats, p13_labels)
        copy_metric_csvs(pair_dir, p14_stats, p14_labels)
        run_final_table(p13_stats, "reference", p13_labels, args.n_boot, args.seed)
        run_final_table(p14_stats, "reference", p14_labels, args.n_boot, args.seed + 100)

    manifest = {
        "repo": args.repo,
        "out": str(out_dir),
        "available_labels": [r["label"] for r in rows],
        "missing": missing,
        "n_boot": args.n_boot,
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    render_md_report(out_dir, configs, rows, missing)
    print(json.dumps(manifest, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
